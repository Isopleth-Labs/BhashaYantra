const dictionaries: Record<InterfaceLanguage, Record<TranslationKey, string>> = {
  en: english,
  hi: hindi,
};

interface I18nValue {
  readonly language: InterfaceLanguage;
  readonly setLanguage: (language: InterfaceLanguage) => void;
  readonly t: (key: TranslationKey, values?: Readonly<Record<string, string | number>>) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { readonly children: ReactNode }) {
  const [language, setLanguage] = useState<InterfaceLanguage>(() =>
    localStorage.getItem("bhashayantra-interface-language") === "en" ? "en" : "hi",
  );

  useEffect(() => {
    document.documentElement.lang = language === "hi" ? "hi" : "en";
    localStorage.setItem("bhashayantra-interface-language", language);
  }, [language]);

  const value = useMemo<I18nValue>(() => ({
    language,
    setLanguage,
    t: (key, values) => {
      let message = dictionaries[language][key];
      for (const [name, replacement] of Object.entries(values ?? {})) {
        message = message.replaceAll(`{${name}}`, String(replacement));
      }
      return message;
    },
  }), [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}
